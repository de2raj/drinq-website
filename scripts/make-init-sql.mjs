// Regenerates src/lib/init-sql.ts from prisma/schema.prisma (run after schema changes: npm run db:sql).
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
const sql = execSync("npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script", { encoding: "utf8" });
writeFileSync("prisma/init.sql", sql);
writeFileSync("src/lib/init-sql.ts", "// Generated by scripts/make-init-sql.mjs — do not edit.\nexport const INIT_SQL = " + JSON.stringify(sql) + ";\n");
console.log("init SQL updated");
