/**
 * Picks the database for this build and prepares Prisma for it.
 *  - Mac / cPanel: SQLite (prisma/schema.prisma as written).
 *  - GoDaddy Node.js Hosting: MySQL (its managed database; files on that platform may not survive a redeploy).
 * Rule: MySQL when DB_PROVIDER=mysql, DB_HOST is set, DATABASE_URL starts with mysql:,
 * or when there is no .env and no DATABASE_URL at all (the GoDaddy build). Otherwise SQLite.
 * Also writes src/lib/db-init.generated.ts (not in git: each build regenerates it for its database).
 * (src/lib/init-sql.ts is an old copy kept unchanged only so GoDaddy's git pull never clashes; it is unused.)
 */
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const env = { ...process.env };
if (existsSync(".env")) {
  for (const line of readFileSync(".env", "utf8").split("\n")) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && env[m[1]] === undefined) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
}
const url = env.DATABASE_URL || "";
const provider =
  env.DB_PROVIDER === "sqlite" ? "sqlite"
  : env.DB_PROVIDER === "mysql" || env.DB_HOST || url.startsWith("mysql:") || (!existsSync(".env") && !url) ? "mysql"
  : "sqlite";

let schema = "prisma/schema.prisma";
if (provider === "mysql") {
  const src = readFileSync(schema, "utf8");
  const out = src
    .replace(/provider\s*=\s*"sqlite"/, 'provider = "mysql"')
    .replace(/\n\s*binaryTargets\s*=.*\n/, "\n")
    // Fields marked "@text" in a comment hold long text (JSON, notes): TEXT columns in MySQL.
    .replace(/^(\s+\w+\s+String\??)([^\n]*?)(\s*\/\/[^\n]*@text[^\n]*)$/gm, (_l, a, b, c) => `${a}${b.replace(/\s*@default\(""\)/, "")} @db.Text${c}`)
    // MySQL's default text column is 191 characters: give free-text fields room.
    .replace(/^(\s+\w+\s+String\??)(?![^\n]*@(?:id|unique|db\.))([^\n]*?)(\s*\/\/[^\n]*)?$/gm, (_l, a, b, c = "") => `${a}${b} @db.VarChar(500)${c}`);
  mkdirSync("prisma/.gen", { recursive: true });
  schema = "prisma/.gen/schema.prisma";
  writeFileSync(schema, out);
}

const run = (cmd) => execSync(cmd, { encoding: "utf8", env: { ...env, DATABASE_URL: url || (provider === "mysql" ? "mysql://u:p@localhost:3306/db" : "file:./drinq.db") } });
run(`npx prisma generate --schema ${schema}`);
const sql = run(`npx prisma migrate diff --from-empty --to-schema-datamodel ${schema} --script`);
writeFileSync("src/lib/db-init.generated.ts",
  "// Generated by scripts/prepare-db.mjs — do not edit.\n" +
  `export const DB_PROVIDER = ${JSON.stringify(provider)} as "sqlite" | "mysql";\n` +
  `export const INIT_SQL = ${JSON.stringify(sql)};\n`);
console.log(`[drinq] Database: ${provider}`);
